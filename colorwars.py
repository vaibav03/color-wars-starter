"""Color Wars core: grid helpers and game rules shared by bot.py and simulate.py.

Do not edit this file. Your strategy may import the helpers below:

    from colorwars import neighbors, distance_map

Squares are named by label, for example "G17". A board is a dict that maps
every label to one of: "me", "enemy", "empty", "wall", "bomb".
"""
import re
from collections import deque

COLS, ROWS = 36, 34
_LABEL = re.compile(r"^([A-Z]{1,2})(\d{1,2})$")


def col_name(i):
    return chr(65 + i) if i < 26 else "A" + chr(65 + i - 26)


def parse(label):
    """'G17' -> (6, 17), or None when the text is not a square label."""
    m = _LABEL.match(label or "")
    if not m:
        return None
    c = m.group(1)
    x = ord(c) - 65 if len(c) == 1 else 26 + ord(c[1]) - 65
    y = int(m.group(2))
    return (x, y) if 0 <= x < COLS and 1 <= y <= ROWS else None


def name(pos):
    return f"{col_name(pos[0])}{pos[1]}"


ALL_SQUARES = [name((x, y)) for y in range(1, ROWS + 1) for x in range(COLS)]


def neighbors(label):
    """The squares that touch `label` on its top, bottom, left or right side."""
    x, y = parse(label)
    out = []
    for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
        if 0 <= nx < COLS and 1 <= ny <= ROWS:
            out.append(name((nx, ny)))
    return out


def distance_map(board, goals):
    """Steps from each square to the nearest goal square, walking around walls.

    Returns a dict label -> steps. Squares that cannot reach a goal are absent.
    """
    dist = {g: 0 for g in goals if board.get(g) != "wall"}
    todo = deque(dist)
    while todo:
        p = todo.popleft()
        for n in neighbors(p):
            if n not in dist and n in board and board[n] != "wall":
                dist[n] = dist[p] + 1
                todo.append(n)
    return dist


def connected(board, crystal, who="me"):
    """The squares `who` owns that still link back to their crystal."""
    # a crystal square counts as a starting point while it is ours, or while the
    # referee is rebuilding it and it is missing from the board
    seen = {c for c in crystal if board.get(c, who) == who}
    todo = deque(seen)
    while todo:
        for n in neighbors(todo.popleft()):
            if n not in seen and board.get(n) == who:
                seen.add(n)
                todo.append(n)
    return seen


def legal_squares(board, crystal, who="me"):
    """Squares `who` can capture right now: next to a connected square, not a wall, not theirs."""
    own = connected(board, crystal, who)
    out = {n for p in own for n in neighbors(p)
           if n in board and board[n] not in (who, "wall")}
    return sorted(out, key=lambda s: (parse(s)[1], parse(s)[0]))


def safe_choose(choose, board, legal, my_crystal, enemy_crystal, reverted, log=print):
    """Call the student's choose() and never let it stop the match.

    Returns a legal square, or None when there is none. Same rule as the arena's sandbox:
    on an error or an illegal answer the first legal square is taken.
    """
    if not legal:
        return None
    try:
        pick = choose(dict(board), list(legal), list(my_crystal), list(enemy_crystal), list(reverted))
    except Exception as e:                          # the first legal square is taken instead
        message = " ".join(str(e).split())[:200]
        log(f"KIT-ERROR choose raised: {type(e).__name__}: {message}")
        return legal[0]
    if pick not in legal:                           # the first legal square is taken instead
        log(f"KIT-WARN illegal square: {pick}"[:120])
        return legal[0]
    return pick


# ---------------------------------------------------------------- rules (used by the simulator)

def capture(owner, who, square, crystals):
    """Apply one capture to `owner` (label -> 'red'|'blue'|'empty'|'wall'|'bomb').

    Returns the number of squares that changed hands, or 0 when the move is illegal.
    """
    if square not in legal_squares(owner, crystals[who], who):
        return 0
    changed = 1
    if owner[square] == "bomb":
        x, y = parse(square)
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                p = (x + dx, y + dy)
                if 0 <= p[0] < COLS and 1 <= p[1] <= ROWS:
                    q = name(p)
                    if owner[q] not in ("wall", who):
                        owner[q] = who
                        changed += 1
    owner[square] = who
    for player, crystal in crystals.items():      # supply lines: cut-off squares go empty
        keep = connected(owner, crystal, player)
        for s, o in owner.items():
            if o == player and s not in keep:
                owner[s] = "empty"
    return changed


def threat(owner, who, crystals, radius=5):
    """Crystal threat score for `who`, from 0 (safe) to 1. Lower is better."""
    other = next(p for p in crystals if p != who)
    cells = [parse(c) for c in crystals[who]]
    near, enemy_near, closest = 0, 0, None
    for s, o in owner.items():
        if o == "wall" or s in crystals[who]:
            continue
        x, y = parse(s)
        d = min(abs(x - cx) + abs(y - cy) for cx, cy in cells)
        if d <= radius:
            near += 1
            if o == other:
                enemy_near += 1
                closest = d if closest is None else min(closest, d)
    if not enemy_near:
        return 0.0
    return 0.5 * enemy_near / near + 0.5 * (radius + 1 - closest) / radius


def view(owner, who):
    """The board as one player sees it: 'me' / 'enemy' in place of colour names."""
    other = {"red": "blue", "blue": "red"}[who]
    swap = {who: "me", other: "enemy"}
    return {s: swap.get(o, o) for s, o in owner.items()}
